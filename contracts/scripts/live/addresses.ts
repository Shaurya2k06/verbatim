// Writes contracts/docs/ADDRESSES.md from contracts/deployments/*.json, so it cannot drift from what was deployed.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { ROOT } from "./lib/env";

const read = (n: string) => JSON.parse(readFileSync(resolve(ROOT, `contracts/deployments/${n}.json`), "utf8"));
const rows = (o: Record<string, unknown>, prefix = ""): string[] =>
  Object.entries(o).flatMap(([k, v]) => (v && typeof v === "object" ? rows(v as Record<string, unknown>, `${prefix}${k}.`) : typeof v === "string" && /^0x[0-9a-fA-F]{40}$/.test(v) ? [`| ${prefix}${k} | \`${v}\` |`] : []));
const hashes = (o: Record<string, unknown>, prefix = ""): string[] =>
  Object.entries(o).flatMap(([k, v]) => (v && typeof v === "object" ? hashes(v as Record<string, unknown>, `${prefix}${k}.`) : typeof v === "string" && /^0x[0-9a-fA-F]{64}$/.test(v) ? [`| ${prefix}${k} | \`${v}\` |`] : []));
const dev = read("devnet");
const sep = read("sepolia");
writeFileSync(
  resolve(ROOT, "contracts/docs/ADDRESSES.md"),
  `# Deployed addresses

Generated by \`contracts/scripts/live/addresses.ts\` from \`contracts/deployments/\`. The frames devnet can reset, and then these change: \`make -C contracts proofs\` rebuilds them. There is no mainnet or L2 deployment yet.

## Leg A: EF frames devnet (chain 1337)

Explorer: https://explorer.altmempool.wtf/

| Contract | Address |
|---|---|
${rows(dev).join("\n")}

${hashes(dev).length ? `Hashes (the account and paymaster values are of the APPROVE-patched runtime):\n\n| Name | Hash |\n|---|---|\n${hashes(dev).join("\n")}\n` : ""}
## Leg B: Sepolia

| Contract | Address |
|---|---|
${rows(sep).join("\n")}

ENS: \`verbatim-demo.eth\`.
`,
);
console.log("wrote contracts/docs/ADDRESSES.md");
